def stress_test_model(eval_model, loader, mechanism, rate):
    eval_model.eval()
    preds_all, true_all = [], []
    mmse_feature_idx = 6 # Index for MMSE

    with torch.no_grad():
        for batch in loader:
            features = batch['features'].to(device)
            feat_masks = batch['feat_masks'].to(device)
            time_enc = batch['time_enc'].to(device)
            p_mask = batch['padding_mask'].to(device)
            stage_targets = batch['stage_labels'].to(device)

            corrupted = features.clone()
            corrupted_masks = feat_masks.clone()
            batch_size = features.size(0)

            # 1. MCAR: Uniform Random Loss
            if mechanism == 'MCAR' and rate > 0.0:
                mask = torch.rand(features.shape, device=device) < rate
                corrupted[mask] = 0.0
                corrupted_masks[mask] = 0.0

            # 2. MNAR: Sick-patient data loss (MMSE feature)
            elif mechanism == 'MNAR' and rate > 0.0:
                batch_mmse = features[:, :, mmse_feature_idx]
                # Note: If features are normalized, adjust threshold accordingly
                sick_mask = (batch_mmse < -1.5) & (p_mask == 1.0)
                mnar_matrix = torch.zeros_like(features, dtype=torch.bool)
                if sick_mask.sum() > 0:
                    mnar_matrix[sick_mask] = torch.rand(sick_mask.sum(), features.shape[-1], device=device) < (rate * 1.5)
                    corrupted[mnar_matrix] = 0.0
                    corrupted_masks[mnar_matrix] = 0.0

            # 3. MODAL_DROP: Total MRI modality drop per patient
            elif mechanism == 'MODAL_DROP' and rate > 0.0:
                drop_mask = torch.rand(batch_size, device=device) < rate
                corrupted[drop_mask, :, 16:23] = 0.0
                corrupted_masks[drop_mask, :, 16:23] = 0.0

            # 4. GAUSSIAN_NOISE: Sensor noise
            elif mechanism == 'NOISE' and rate > 0.0:
                valid_data_mask = (corrupted_masks == 1.0)
                noise = torch.randn_like(corrupted) * rate
                corrupted[valid_data_mask] += noise[valid_data_mask]

            # Forward Pass (matching Cell 11 signature)
            outputs = eval_model(corrupted, corrupted_masks, time_enc, padding_mask=p_mask)

            # FIXED: Ordinal Decoding (Matching Cell 11 exactly)
            stage_probs_raw = torch.sigmoid(outputs['stage_logits'])
            stage_preds = (stage_probs_raw >= 0.5).sum(dim=-1)

            # Valid predictions mask
            mask_s = (stage_targets != -1) & (p_mask == 1.0)

            preds_all.extend(stage_preds[mask_s].cpu().numpy())
            true_all.extend(stage_targets[mask_s].cpu().numpy())

    return f1_score(true_all, preds_all, average='macro', zero_division=0)

