def bar_panel(ax, df, value_col, title, xlabel):

    def pick_color(name):

        if OUR_LABEL in name:
            return OURS_COLOR

        if name in [
            "LSTM",
            "CNN-LSTM",
            "Transformer",
            "GNN",
            "CognitiveTwin"
        ]:
            return PAPER_COLOR

        return LIT_COLOR


    colors = [
        pick_color(x)
        for x in df["model"]
    ]


    bars = ax.barh(
        df["model"],
        df[value_col],
        color=colors,
        edgecolor="black"
    )


    ax.set_title(
        title,
        fontsize=12,
        fontweight="bold"
    )

    ax.set_xlabel(xlabel)


    for bar,val in zip(
        bars,
        df[value_col]
    ):

        ax.text(
            val + max(df[value_col])*0.015,
            bar.get_y()+bar.get_height()/2,
            f"{val:.3f}",
            va="center",
            fontsize=8,
            fontweight="bold"
        )


    ax.grid(
        axis="x",
        linestyle="--",
        alpha=0.4
    )



