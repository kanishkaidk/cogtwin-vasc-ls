# 3. UNCERTAINTY-WEIGHTED LOSS WITH ORDINAL DYNAMICS
# Toggle this to True to test "supervise Stage/Conversion on the last
# observed visit only" as a genuine ablation, rather than by argument.
# ELBO and MMSE always stay all-visit either way (nobody disputes those).
SUPERVISE_LAST_VISIT_ONLY = False

class UncertaintyDMM_Loss(nn.Module):
    def __init__(self, class_weights, conv_pos_weight):
        super().__init__()
        self.log_vars = nn.Parameter(torch.zeros(3))
        self.class_weights_tensor = torch.tensor(class_weights, dtype=torch.float32).to(device)
        self.conv_pos_weight = torch.tensor([conv_pos_weight], dtype=torch.float32).to(device)

    def forward(self, outputs, batch, alpha_elbo=0.1):
        pm = batch['padding_mask'].to(device)
        s_t, c_t, m_t = batch['stage_labels'].to(device), batch['convert_labels'].to(device), batch['mmse_targets'].to(device)
        valid_tokens = pm.sum().clamp(min=1)

        if SUPERVISE_LAST_VISIT_ONLY:
            last_idx = pm.sum(dim=1).long().clamp(min=1) - 1
            supervise_mask = torch.zeros_like(pm, dtype=torch.bool)
            supervise_mask.scatter_(1, last_idx.unsqueeze(1), True)
            supervise_mask = supervise_mask & (pm == 1.0)
        else:
            supervise_mask = (pm == 1.0)

        # ELBO
        recon_err = F.mse_loss(outputs['x_recon'], outputs['transformer_target'], reduction='none').mean(dim=-1)
        kl_raw = 0.5 * (outputs['p_logvar'] - outputs['q_logvar'] + torch.exp(outputs['q_logvar'] - outputs['p_logvar']) +
                       ((outputs['q_mu'] - outputs['p_mu']) ** 2) / torch.exp(outputs['p_logvar']) - 1.0)

        elbo_loss = ((recon_err * pm).sum() + (kl_raw.sum(dim=-1) * pm).sum()) / valid_tokens

        # TRUE ORDINAL LOSS (Cumulative BCE Targets)
        s_mask = (s_t != -1) & supervise_mask
        if s_mask.sum() > 0:
            target_stages = s_t[s_mask]
            logits_masked = outputs['stage_logits'][s_mask]

            binary_targets = torch.zeros_like(logits_masked)
            for k in range(3):
                binary_targets[:, k] = (target_stages > k).float()

            weight_tensor = self.class_weights_tensor[1:4]

            bce_ordinal = F.binary_cross_entropy_with_logits(logits_masked, binary_targets, reduction='none')
            pt_ord = torch.exp(-bce_ordinal)
            stage_loss_raw = (weight_tensor * ((1.0 - pt_ord) ** 2) * bce_ordinal).mean()

            stage_loss = torch.exp(-self.log_vars[0]) * stage_loss_raw + 0.5 * self.log_vars[0]
        else: stage_loss = torch.tensor(0.0, device=device)

        # HEAD 2: FOCAL BCE LOSS
        c_mask = (c_t != -1.0) & supervise_mask
        if c_mask.sum() > 0:
            bce_raw = F.binary_cross_entropy_with_logits(outputs['convert_logits'][c_mask], c_t[c_mask], reduction='none')
            pt_c = torch.exp(-bce_raw)
            cw_tensor = torch.where(c_t[c_mask] == 1.0, self.conv_pos_weight, torch.tensor(1.0, device=device))

            conv_loss_raw = (cw_tensor * ((1.0 - pt_c) ** 2) * bce_raw).mean()
            convert_loss = torch.exp(-self.log_vars[1]) * conv_loss_raw + 0.5 * self.log_vars[1]
        else: convert_loss = torch.tensor(0.0, device=device)

        # HEAD 3: HUBER LOSS (was plain MSE)
        # MSE lets a handful of large-decline outliers (rapid decliners) dominate
        # the gradient and drag the whole regression around them. Huber
        # (smooth L1) behaves like MSE near zero (still sensitive to small
        # errors) but degrades to L1 for large residuals, which is more robust
        # to those outliers and tends to lower MAE specifically (even if MSE/RMSE
        # barely moves) because it stops the loss from being outlier-dominated.
        m_mask = (m_t != -1.0) & (pm == 1.0)
        if m_mask.sum() > 0:
            mmse_loss_raw = F.smooth_l1_loss(outputs['mmse_pred'][m_mask] / 30.0, m_t[m_mask] / 30.0, beta=0.05)
            mmse_loss = 0.5 * torch.exp(-self.log_vars[2]) * mmse_loss_raw + 0.5 * self.log_vars[2]
        else: mmse_loss = torch.tensor(0.0, device=device)

        return (alpha_elbo * elbo_loss) + stage_loss + convert_loss + mmse_loss, {}

