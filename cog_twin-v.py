class CrossModalTransformerFusion(nn.Module):
    def __init__(self, hidden_dim=256, n_heads=8, num_layers=4, dropout=0.1):
        super().__init__()
        self.proj_cog  = nn.Linear(8 * 2, hidden_dim)
        self.proj_bio  = nn.Linear(8 * 2, hidden_dim)
        self.proj_mri  = nn.Linear(7 * 2, hidden_dim)
        self.proj_gen  = nn.Linear(1 * 2, hidden_dim)
        self.proj_vasc = nn.Linear(10 * 2, hidden_dim)
        self.proj_prog = nn.Linear(6 * 2, hidden_dim)  # NEW: progression/delta modality

        self.register_buffer("modality_ids", torch.arange(6))
        self.modality_embed = nn.Embedding(6, hidden_dim)

        # Learnable CLS Token for optimal feature fusion
        self.cls_token = nn.Parameter(torch.randn(1, 1, hidden_dim))

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=hidden_dim, nhead=n_heads, dim_feedforward=hidden_dim * 2,
            dropout=dropout, batch_first=True, norm_first=True
        )
        # Suppress PyTorch 2.0+ Nested Tensor warning
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers, enable_nested_tensor=False)

    def forward(self, c_f, c_m, b_f, b_m, m_f, m_m, g_f, g_m, v_f, v_m, p_f, p_m):
        N = c_f.size(0)

        c = self.proj_cog(torch.cat([c_f, c_m], dim=-1)).unsqueeze(1) + self.modality_embed(self.modality_ids[0])
        b = self.proj_bio(torch.cat([b_f, b_m], dim=-1)).unsqueeze(1) + self.modality_embed(self.modality_ids[1])
        m = self.proj_mri(torch.cat([m_f, m_m], dim=-1)).unsqueeze(1) + self.modality_embed(self.modality_ids[2])
        g = self.proj_gen(torch.cat([g_f, g_m], dim=-1)).unsqueeze(1) + self.modality_embed(self.modality_ids[3])
        v = self.proj_vasc(torch.cat([v_f, v_m], dim=-1)).unsqueeze(1) + self.modality_embed(self.modality_ids[4])
        p = self.proj_prog(torch.cat([p_f, p_m], dim=-1)).unsqueeze(1) + self.modality_embed(self.modality_ids[5])

        cls_tokens = self.cls_token.expand(N, -1, -1)
        tokens = torch.cat([cls_tokens, c, b, m, g, v, p], dim=1)

        # FIXED: Added .unsqueeze(1) to force all masks to be 2D [N, 1]
        cls_mask = torch.zeros(N, 1, dtype=torch.bool, device=c_f.device)
        c_mask = (c_m.sum(dim=-1) == 0).unsqueeze(1)
        b_mask = (b_m.sum(dim=-1) == 0).unsqueeze(1)
        m_mask = (m_m.sum(dim=-1) == 0).unsqueeze(1)
        g_mask = (g_m.sum(dim=-1) == 0).unsqueeze(1)
        v_mask = (v_m.sum(dim=-1) == 0).unsqueeze(1)
        p_mask = (p_m.sum(dim=-1) == 0).unsqueeze(1)

        # Now [N, 7] concatenates perfectly (CLS + 6 modalities)
        key_padding_mask = torch.cat([cls_mask, c_mask, b_mask, m_mask, g_mask, v_mask, p_mask], dim=1)

        fused = self.transformer(tokens, src_key_padding_mask=key_padding_mask)
        return fused[:, 0, :]

class GatedTransition(nn.Module):
    def __init__(self, latent_dim):
        super().__init__()
        self.gate = nn.Sequential(nn.Linear(latent_dim, latent_dim), nn.Sigmoid())
        self.proposed_mean = nn.Sequential(nn.Linear(latent_dim, latent_dim), nn.ReLU(), nn.Linear(latent_dim, latent_dim))
        self.z_to_logvar = nn.Linear(latent_dim, latent_dim)

    def forward(self, z_prev):
        g = self.gate(z_prev)
        h = self.proposed_mean(z_prev)
        mean = (1 - g) * z_prev + g * h
        logvar = self.z_to_logvar(z_prev)
        return mean, logvar

class CognitiveTwinDMM(nn.Module):
    def __init__(self, hidden_dim=256, latent_dim=64, dropout=0.1):
        super().__init__()
        self.latent_dim = latent_dim
        self.spatial_fusion = CrossModalTransformerFusion(hidden_dim, n_heads=8, num_layers=4, dropout=dropout)

        self.seq_time_embed = nn.Embedding(250, hidden_dim)

        temporal_layer = nn.TransformerEncoderLayer(
            d_model=hidden_dim, nhead=8, dim_feedforward=hidden_dim * 2,
            dropout=dropout, batch_first=True, norm_first=True
        )
        self.temporal_transformer = nn.TransformerEncoder(temporal_layer, num_layers=2, enable_nested_tensor=False)

        # Filtering Posterior (Forward-Only GRU -> 100% Causal)
        self.rnn_encoder = nn.GRU(hidden_dim, hidden_dim // 2, num_layers=2, batch_first=True, bidirectional=False, dropout=dropout)

        self.q_z_mean = nn.Linear(hidden_dim // 2, latent_dim)
        self.q_z_logvar = nn.Linear(hidden_dim // 2, latent_dim)
        self.trans_p = GatedTransition(latent_dim)
        self.emission_decoder = nn.Sequential(nn.Linear(latent_dim, hidden_dim), nn.ReLU(), nn.Linear(hidden_dim, hidden_dim))

        self.causal_proj = nn.Linear(hidden_dim + latent_dim, latent_dim)

        # ORDINAL HEAD: 3 outputs to match BCEWithLogitsLoss
        self.stage_head = nn.Sequential(nn.LayerNorm(latent_dim), nn.Linear(latent_dim, 256), nn.GELU(), nn.Dropout(0.2), nn.Linear(256, 128), nn.GELU(), nn.Linear(128, 3))
        self.convert_head = nn.Sequential(nn.LayerNorm(latent_dim), nn.Linear(latent_dim, 64), nn.ReLU(), nn.Linear(64, 1))
        self.mmse_head = nn.Sequential(nn.LayerNorm(latent_dim), nn.Linear(latent_dim, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, features, feat_masks, time_enc, padding_mask=None):
        batch_size, max_visits, _ = features.shape

        c_f, c_m = features[:, :, 0:8].contiguous().view(-1, 8), feat_masks[:, :, 0:8].contiguous().view(-1, 8)
        b_f, b_m = features[:, :, 8:16].contiguous().view(-1, 8), feat_masks[:, :, 8:16].contiguous().view(-1, 8)
        m_f, m_m = features[:, :, 16:23].contiguous().view(-1, 7), feat_masks[:, :, 16:23].contiguous().view(-1, 7)
        g_f, g_m = features[:, :, 23:24].contiguous().view(-1, 1), feat_masks[:, :, 23:24].contiguous().view(-1, 1)
        v_f, v_m = features[:, :, 24:34].contiguous().view(-1, 10), feat_masks[:, :, 24:34].contiguous().view(-1, 10)
        p_f, p_m = features[:, :, 34:40].contiguous().view(-1, 6), feat_masks[:, :, 34:40].contiguous().view(-1, 6)

        fused_flat = self.spatial_fusion(c_f, c_m, b_f, b_m, m_f, m_m, g_f, g_m, v_f, v_m, p_f, p_m)
        fused_sequence = fused_flat.view(batch_size, max_visits, -1)

        t_idx = torch.clamp(time_enc.long(), 0, 249)
        fused_sequence = fused_sequence + self.seq_time_embed(t_idx)

        causal_mask = nn.Transformer.generate_square_subsequent_mask(max_visits).to(features.device)
        # FIXED: explicitly exclude padded visit slots from attention (previously
        # only relied on right-padding + causal masking to keep them harmless).
        key_padding = ~padding_mask.bool() if padding_mask is not None else None
        temporal_out = self.temporal_transformer(
            fused_sequence, mask=causal_mask, src_key_padding_mask=key_padding, is_causal=True
        )

        rnn_out, _ = self.rnn_encoder(temporal_out)
        q_mu = self.q_z_mean(rnn_out)
        q_logvar = self.q_z_logvar(rnn_out)
        z_sampled = self.reparameterize(q_mu, q_logvar)

        # FIXED: teacher-forced prior. The previous version fed the previous
        # PRIOR MEAN back into trans_p, which never touches z_sampled/q_mu at
        # all after t=0 -- since that chain starts from the same zeros for
        # every patient, p_mu_tensor ended up IDENTICAL across the whole
        # batch at every timestep, regardless of the patient's actual data.
        # The KL term was regularizing every patient's posterior toward one
        # shared, data-blind trajectory instead of a real transition prior.
        # Fix: condition the prior at t on the ACTUAL posterior sample at
        # t-1 (teacher forcing), matching the reference repo's dmm.py.
        p_mu_list, p_logvar_list = [], []
        for t in range(max_visits):
            if t == 0:
                p_mu = torch.zeros(batch_size, self.latent_dim, device=features.device)
                p_logvar = torch.zeros(batch_size, self.latent_dim, device=features.device)
            else:
                p_mu, p_logvar = self.trans_p(z_sampled[:, t - 1, :])  # teacher-forced on real posterior
            p_mu_list.append(p_mu.unsqueeze(1))
            p_logvar_list.append(p_logvar.unsqueeze(1))

        p_mu_tensor = torch.cat(p_mu_list, dim=1)
        p_logvar_tensor = torch.cat(p_logvar_list, dim=1)

        # Because rnn_encoder is now forward-only (Filtering), z_sampled has NO future leakage
        causal_input = torch.cat([temporal_out, z_sampled], dim=-1)
        z_causal = self.causal_proj(causal_input)

        return {
            'stage_logits': self.stage_head(z_causal),
            'convert_logits': self.convert_head(z_causal).squeeze(-1),
            'mmse_pred': self.mmse_head(z_causal).squeeze(-1),
            'x_recon': self.emission_decoder(z_sampled), 'transformer_target': fused_sequence,
            'q_mu': q_mu, 'q_logvar': q_logvar, 'p_mu': p_mu_tensor, 'p_logvar': p_logvar_tensor
        }

    def reparameterize(self, mu, logvar):
        # FIXED: this always sampled (torch.randn_like), even in model.eval()
        # mode, so every inference pass drew a fresh z and every downstream
        # metric (Head 2 AUC, Head 3 MAE, SHAP, fairness audit) was computed
        # on a different random latent draw each time the same checkpoint was
        # evaluated -- exactly explaining run-to-run metric drift on identical
        # weights. Standard practice for VAEs/DMMs: sample during training
        # (z = mu + sigma*eps, for a pathwise gradient through the KL term),
        # but use the deterministic posterior mean at inference (z = mu).
        if self.training:
            std = torch.exp(0.5 * logvar)
            return mu + torch.randn_like(std) * std
        else:
            return mu

