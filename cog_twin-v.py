import pandas as pd
import numpy as np

# Ensure everything remains cleanly sorted chronologically per patient
tadpole = tadpole.sort_values(by=['RID', 'EXAMDATE']).copy()

# ---------------------------------------------------------------------------
# HEAD 1: stage_label (4-class, uses CURRENT visit CDR and DX)
# ---------------------------------------------------------------------------
def assign_stage(row):
    dx = row['DX_current']
    cdrsb = row['CDRSB']

    # Both DX and CDRSB must be present
    if pd.isna(dx) or pd.isna(cdrsb):
        return np.nan

    # Class 0: NOT Alzheimer's Disease
    # TADPOLE uses 'NL' (not 'CN') for cognitively normal patients
    if dx in ['NL', 'CN', 'MCI']:
        return 0

    # Class 1/2/3: Confirmed Dementia — sub-staged by CDR severity
    if dx == 'Dementia':
        if cdrsb <= 5.5:
            return 1   # Mild AD (CDR global ≈ 0.5–1)
        elif cdrsb <= 11.5:
            return 2   # Moderate AD (CDR global ≈ 2)
        else:
            return 3   # Severe AD (CDR global ≈ 3)

    return np.nan
tadpole['stage_label'] = tadpole.apply(assign_stage, axis=1)

print("--- HEAD 1: stage_label Distribution ---")
print(tadpole['stage_label'].value_counts(dropna=False))


# ---------------------------------------------------------------------------
# HEAD 2: convert_label (36-month horizon, MCI rows only)
# ---------------------------------------------------------------------------
tadpole['convert_label'] = np.nan

# Group by patient to scan their individual progression histories
for rid, group in tadpole.groupby('RID'):
    mci_indices = group[group['DX_current'] == 'MCI'].index

    for idx in mci_indices:
        current_date = group.loc[idx, 'EXAMDATE']
        horizon_end = current_date + pd.DateOffset(months=36)

        # Look ahead at follow-up records within the 36-month window
        future_visits = group[(group['EXAMDATE'] > current_date) & (group['EXAMDATE'] <= horizon_end)]

        if future_visits.empty:
            # No follow-up data available within the tracking frame
            tadpole.loc[idx, 'convert_label'] = np.nan
        elif (future_visits['DX_current'] == 'Dementia').any():
            # Conversion to dementia confirmed within 36 months
            tadpole.loc[idx, 'convert_label'] = 1.0
        else:
            # Followed up within 36 months and did not progress to dementia
            tadpole.loc[idx, 'convert_label'] = 0.0

print("\n--- HEAD 2: convert_label Distribution (MCI Rows Only) ---")
print(tadpole[tadpole['DX_current'] == 'MCI']['convert_label'].value_counts(dropna=False))


# ---------------------------------------------------------------------------
# HEAD 3: mmse_24mo (24-month regression target, all patients)
# ---------------------------------------------------------------------------
tadpole['mmse_24mo'] = np.nan

for rid, group in tadpole.groupby('RID'):
    for idx, row in group.iterrows():
        target_date = row['EXAMDATE'] + pd.DateOffset(months=24)

        # Find visits within an acceptable window around the 24-month mark (±3 months)
        window_start = target_date - pd.DateOffset(months=3)
        window_end = target_date + pd.DateOffset(months=3)

        matched_visits = group[(group['EXAMDATE'] >= window_start) & (group['EXAMDATE'] <= window_end)]

        if not matched_visits.empty:
            # Force numeric evaluation to grab the closest real score entry
            valid_mmse = matched_visits[pd.to_numeric(matched_visits['MMSE'], errors='coerce').notna()]
            if not valid_mmse.empty:
                # Target the record chronologically closest to our window objective
                closest_idx = (valid_mmse['EXAMDATE'] - target_date).abs().idxmin()
                tadpole.loc[idx, 'mmse_24mo'] = pd.to_numeric(valid_mmse.loc[closest_idx, 'MMSE'])

print("\n--- HEAD 3: mmse_24mo Availability ---")
valid_count = tadpole['mmse_24mo'].notna().sum()
print(f"Rows with valid 24-mo MMSE regression target: {valid_count} / {len(tadpole)} ({valid_count/len(tadpole):.1%})")


