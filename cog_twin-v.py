# 2. SEQUENCE PADDING AND BATCH COLLATOR
# ---------------------------------------------------------------------------
def adni_collate_fn(batch):
    """
    Dynamic batch padding collator to safely equalize variable-length patient timelines.
    """
    # Identify the longest longitudinal visit history within the current batch slice
    max_len = max(x['features'].size(0) for x in batch)
    num_features = batch[0]['features'].size(1)

    batch_size = len(batch)

    # Initialize uniform tensor blocks pre-filled with appropriate default values
    padded_features = torch.zeros((batch_size, max_len, num_features), dtype=torch.float32)
    padded_masks = torch.zeros((batch_size, max_len, num_features), dtype=torch.float32)
    padded_time = torch.zeros((batch_size, max_len), dtype=torch.float32)

    # Target sequences use -1 / -1.0 tracking flags to skip loss calculations on padded rows
    padded_stage = torch.full((batch_size, max_len), -1, dtype=torch.long)
    padded_convert = torch.full((batch_size, max_len), -1.0, dtype=torch.float32)
    padded_mmse = torch.full((batch_size, max_len), -1.0, dtype=torch.float32)

    # Binary padding mask: 1.0 indicates a real clinical visit, 0.0 indicates a padded step
    padding_mask = torch.zeros((batch_size, max_len), dtype=torch.float32)

    for i, patient in enumerate(batch):
        seq_len = patient['features'].size(0)

        # Insert authentic patient timelines into the batched structures
        padded_features[i, :seq_len, :] = patient['features']
        padded_masks[i, :seq_len, :] = patient['masks']
        padded_time[i, :seq_len] = patient['time_months']
        padded_stage[i, :seq_len] = patient['stage_labels']
        padded_convert[i, :seq_len] = patient['convert_labels']
        padded_mmse[i, :seq_len] = patient['mmse_targets']

        padding_mask[i, :seq_len] = 1.0

    return {
        'features': padded_features,
        'feat_masks': padded_masks,
        'time_enc': padded_time,
        'stage_labels': padded_stage,
        'convert_labels': padded_convert,
        'mmse_targets': padded_mmse,
        'padding_mask': padding_mask
    }

