def bootstrap_test(y_true, model_preds, baseline_preds, metric_func, **kwargs):
    model_scores, base_scores = [], []
    for i in range(1000):
        idx = resample(np.arange(len(y_true)), random_state=i)
        if len(np.unique(y_true[idx])) < 2: continue
        model_scores.append(metric_func(y_true[idx], model_preds[idx], **kwargs))
        base_scores.append(metric_func(y_true[idx], baseline_preds[idx], **kwargs))

    m_mean, b_mean = np.mean(model_scores), np.mean(base_scores)
    ci = np.percentile(model_scores, [2.5, 97.5])

    if metric_func == mean_absolute_error: p_val = np.mean(np.array(base_scores) <= np.array(model_scores))
    else: p_val = np.mean(np.array(base_scores) >= np.array(model_scores))
